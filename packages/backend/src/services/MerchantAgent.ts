  /**
   * Generate discount strategy recommendations
   */
  async generateDiscountStrategy(
    merchantId: string,
    config: MerchantConfig | null
  ): Promise<MerchantInsight> {
    // Gather discount-relevant data
    const failureReasons = await this.analyticsService.getPaymentFailureReasons(merchantId);
    const metrics = await this.analyticsService.getDashboardMetrics(merchantId);
    const maxDiscount = config?.max_discount_percent || 30;

    // Build prompt (include max_discount as constraint)
    const prompt = this.buildDiscountPrompt(failureReasons, metrics, maxDiscount);

    // Call Claude
    const response = await this.callGroqAPI(prompt);
    const parsed = this.parseRecommendationResponse(response, []);

    // CRITICAL: Enforce max_discount_percent guard rail
    const guardRailsApplied: string[] = [];
    for (const insight of parsed.insights) {
      // Extract discount value if present in insight
      const discountMatch = insight.description.match(/(\d+)%?\s*discount/i);
      if (discountMatch) {
        const recommendedDiscount = parseInt(discountMatch[1]);
        if (recommendedDiscount > maxDiscount) {
          insight.description = insight.description.replace(
            /(\d+)%?\s*discount/i,
            `${maxDiscount}% discount`
          );
          guardRailsApplied.push(
            `discount_capped_to_${maxDiscount}% (recommended: ${recommendedDiscount}%)`
          );
        }
      }
    }

    // Enforce guard rails
    const withGuardRails = this.enforceGuardRails(parsed, config);
    withGuardRails.guard_rails_applied = [
      ...(withGuardRails.guard_rails_applied || []),
      ...guardRailsApplied,
    ];

    return {
      type: 'discount_strategy',
      title: 'Discount Strategy Recommendations',
      summary: withGuardRails.summary,
      insights: withGuardRails.insights,
      data_summary: {
        max_discount_allowed: maxDiscount,
        top_failure_reason: failureReasons.reasons[0]?.reason,
        revenue_at_risk: metrics.revenue_at_risk_cents,
      },
      generated_at: new Date(),
      confidence_percent: withGuardRails.confidence,
      guard_rails_applied: withGuardRails.guard_rails_applied,
    };
  }

