  /**
   * Call Groq API (same pattern as RecommendationService)
   */
  private async callGroqAPI(prompt: string): Promise<GroqResponse> {
    if (!env.GROQ_API_KEY) {
      throw new Error('GROQ_API_KEY not configured');
    }

    try {
      const response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${env.GROQ_API_KEY}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: MerchantAgent.MODEL,
          messages: [
            {
              role: 'system',
              content: 'You are a merchant intelligence analyst providing insights for e-commerce recovery.',
            },
            {
              role: 'user',
              content: prompt,
            },
          ],
          temperature: MerchantAgent.TEMPERATURE,
          max_tokens: MerchantAgent.MAX_TOKENS,
          response_format: { type: 'json_object' },
        }),
      });

      if (!response.ok) {
        throw new Error(`Groq API error: ${response.status}`);
      }

      return (await response.json()) as GroqResponse;
    } catch (error) {
      console.error('[MerchantAgent] Groq API error:', error);
      throw new Error('AI service temporarily unavailable');
    }
  }

  /**
   * Parse analysis response from Claude
   */
  private parseAnalysisResponse(response: GroqResponse): {
    summary: string;
    insights: InsightRecommendation[];
    confidence: number;
  } {
    try {
      const text = response.choices[0]?.message.content || '';
      const data = JSON.parse(text);

      return {
        summary: data.summary || 'No summary available',
        insights: data.insights || [],
        confidence: data.confidence_percent || 70,
      };
    } catch (error) {
      console.error('[MerchantAgent] Failed to parse response:', error);
      return {
        summary: 'Failed to generate analysis',
        insights: [],
        confidence: 0,
      };
    }
  }

  /**
   * Parse recommendation response from Claude
   */
  private parseRecommendationResponse(
    response: GroqResponse,
    validProducts: Product[]
  ): {
    summary: string;
    insights: InsightRecommendation[];
    confidence: number;
  } {
    try {
      const text = response.choices[0]?.message.content || '';
      const data = JSON.parse(text);

      // Validate insights structure
      const insights = (data.insights || []).map((i: any) => ({
        title: i.title || 'Recommendation',
        description: i.description || '',
        reasoning: i.reasoning || '',
        action: i.action || '',
        priority: i.priority || 'medium',
        confidence_percent: Math.min(100, Math.max(0, i.confidence_percent || 70)),
        data_sources: i.data_sources || [],
        limitations: i.limitations,
      }));

      return {
        summary: data.summary || 'Recommendations generated',
        insights,
        confidence: Math.min(100, Math.max(0, data.confidence_percent || 70)),
      };
    } catch (error) {
      console.error('[MerchantAgent] Failed to parse recommendation:', error);
      return {
        summary: 'Recommendation generation failed',
        insights: [],
        confidence: 0,
      };
    }
  }

  /**
   * Enforce guard rails on all recommendations (CRITICAL)
   */
  private enforceGuardRails(
    parsed: {
      summary: string;
      insights: InsightRecommendation[];
      confidence: number;
    },
    config: MerchantConfig | null
  ): {
    summary: string;
    insights: InsightRecommendation[];
    confidence: number;
    guard_rails_applied: string[];
  } {
    const guardRailsApplied: string[] = [];

    // Filter insights by confidence threshold
    const minConfidence = config?.min_confidence_score || 70;
    const filtered = parsed.insights.filter((i) => i.confidence_percent >= minConfidence);

    if (filtered.length < parsed.insights.length) {
      guardRailsApplied.push(
        `${parsed.insights.length - filtered.length} insights filtered below confidence threshold`
      );
    }

    return {
      summary: parsed.summary,
      insights: filtered,
      confidence: parsed.confidence,
      guard_rails_applied: guardRailsApplied,
    };
  }

