  /**
   * Get abandoned carts data
   */
  private async getAbandonedCarts(): Promise<
    Array<{ product_id: string; product_name: string; abandon_count: number }>
  > {
    try {
      // Query carts with items but no completed orders
      const result = await this.dataSource
        .createQueryBuilder()
        .select('ci.product_id', 'product_id')
        .addSelect('p.name', 'product_name')
        .addSelect('COUNT(ci.id)', 'abandon_count')
        .from(CartItem, 'ci')
        .innerJoin(Cart, 'c', 'c.id = ci.cart_id')
        .innerJoin(Product, 'p', 'p.id = ci.product_id')
        .where("c.status = 'pending'")
        .groupBy('ci.product_id, p.name')
        .orderBy('COUNT(ci.id)', 'DESC')
        .limit(20)
        .getRawMany();

      return result;
    } catch (error) {
      console.error('[MerchantAgent] Error fetching abandoned carts:', error);
      return [];
    }
  }

