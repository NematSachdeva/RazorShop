/**
 * M8 Merchant Agent Service
 * 
 * Core logic for generating AI-driven merchant insights.
 * 
 * Responsibilities:
 * 1. Gather merchant transactional data via AnalyticsService
 * 2. Build deterministic analysis prompts
 * 3. Call Claude (Groq) API for insights
 * 4. Validate and enforce guard rails on recommendations
 * 5. Return structured insights ready for storage
 * 
 * Architecture:
 * - Uses existing AnalyticsService for data queries (no duplication)
 * - Follows RecommendationService pattern for Claude integration
 * - Validates all AI output before returning
 * - Guard rails enforced in application code (not AI prompt)
 */

