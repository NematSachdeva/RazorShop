/**
 * Insight types generated by MerchantAgent
 */
export type InsightType = 
  | 'payment_failure_patterns'
  | 'abandoned_cart_patterns'
  | 'recovery_success_rates'
  | 'product_bundles'
  | 'discount_strategy'
  | 'inventory_optimization'
  | 'recovery_targeting';

/**
 * Individual insight recommendation
 */
export interface InsightRecommendation {
  title: string;
  description: string;
  reasoning: string;
  action: string;
  priority: 'high' | 'medium' | 'low';
  confidence_percent: number;
  data_sources: string[];
  limitations?: string;
}

/**
 * Complete insight with metadata
 */
export interface MerchantInsight {
  type: InsightType;
  title: string;
  summary: string;
  insights: InsightRecommendation[];
  data_summary: Record<string, unknown>;
  generated_at: Date;
  confidence_percent: number;
  guard_rails_applied?: string[];
}

/**
 * Groq API response structure
 */
interface GroqResponse {
  choices: Array<{
    message: {
      content: string;
    };
  }>;
}

